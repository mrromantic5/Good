// Generates src/icons.gen.ts — only the icons CineFliX uses, as raw SVG path
// data from Font Awesome Free 6.5.1 (CC BY 4.0). Replaces the ~250 KB icon font.
import { readFileSync, writeFileSync } from 'node:fs';

const FA = 'node_modules/@fortawesome/fontawesome-free/svgs/';
const MAP = {
  play: 'solid/play', pause: 'solid/pause', bookmark: 'solid/bookmark', 'bookmark-o': 'regular/bookmark',
  info: 'solid/circle-info', 'chevron-left': 'solid/chevron-left', 'chevron-right': 'solid/chevron-right',
  'chevron-down': 'solid/chevron-down', trailer: 'solid/clapperboard', pip: 'solid/clone', cc: 'regular/closed-captioning',
  'comment-o': 'regular/comment', download: 'solid/download', expand: 'solid/expand', compress: 'solid/compress',
  next: 'solid/forward-step', futbol: 'solid/futbol', heart: 'solid/heart', 'heart-o': 'regular/heart',
  pin: 'solid/location-dot', search: 'solid/magnifying-glass', send: 'solid/paper-plane', back10: 'solid/rotate-left',
  fwd10: 'solid/rotate-right', share: 'solid/share-nodes', star: 'solid/star', broadcast: 'solid/tower-broadcast',
  'trash-o': 'regular/trash-can', external: 'solid/up-right-from-square', user: 'solid/user', 'vol-high': 'solid/volume-high',
  'vol-low': 'solid/volume-low', 'vol-off': 'solid/volume-xmark', x: 'solid/xmark', house: 'solid/house', film: 'solid/film',
  tv: 'solid/tv', compass: 'solid/compass', bell: 'solid/bell', calendar: 'regular/calendar', table: 'solid/table-list',
  wifi: 'solid/wifi', warn: 'solid/triangle-exclamation', check: 'solid/check', gear: 'solid/gear',
  enhance: 'solid/wand-magic-sparkles', bolt: 'solid/bolt', clapper: 'solid/clapperboard'
};

const out = {};
for (const [name, file] of Object.entries(MAP)) {
  const svg = readFileSync(FA + file + '.svg', 'utf8');
  const vb = svg.match(/viewBox="([^"]+)"/)[1];
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
  out[name] = [vb, d];
}
writeFileSync('src/icons.gen.ts',
  '// AUTO-GENERATED by scripts/icons.mjs — do not edit.\n// Icons: Font Awesome Free 6.5.1 by @fontawesome — https://fontawesome.com (CC BY 4.0)\n' +
  'export const ICONS = ' + JSON.stringify(out) + ' as const;\nexport type IconName = keyof typeof ICONS;\n');
console.log('icons:', Object.keys(out).length);
